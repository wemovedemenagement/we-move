import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {normalizeTechnicalVisit,inventoryVolume} from '../shared/technicalVisit.mjs';
import {emptyQuoteDocument,prefillQuoteDraft} from '../shared/quoteDocument.mjs';
process.env.CRM_STORAGE='sqlite';
process.env.CRM_DATA_DIR=mkdtempSync(path.join(tmpdir(),'wemove-visit-'));
process.env.CRM_LEAD_NOTIFICATIONS='false';process.env.CRM_CUSTOMER_RECEIPTS='false';
const store=await import('../server/crmStore.mjs');
const access={floor:'2',elevator:'Non',carry:'25',notes:'Passage étroit : 75 cm'};
const visit={items:[{room:'Séjour',label:' Canapé ',quantity:2,unitVolume:1.5}],departure:access,arrival:{floor:'',elevator:'',carry:'',notes:''}};
assert.equal(inventoryVolume(visit.items),3);
for(const bad of [null,[],{...visit,extra:true},{...visit,items:[{...visit.items[0],quantity:1.5}]},{...visit,items:[{...visit.items[0],unitVolume:0}]},{...visit,items:[{...visit.items[0],quantity:500,unitVolume:100}]},{...visit,departure:{...access,elevator:'peut-être'}},{...visit,arrival:{...access,carry:'-1'}}])assert.throws(()=>normalizeTechnicalVisit(bad),{status:400});
let lead=await store.createQuoteLead({fullName:'Visite isolée',email:'test@example.invalid',volume:20});
lead=await store.updateQuoteLead(lead.id,{technicalVisit:visit,expectedUpdatedAt:lead.updatedAt});
assert.equal(lead.volume,20,'Inventory never silently replaces the project volume');
assert.equal(lead.technicalVisit.items[0].label,'Canapé');
assert.match(lead.internalNotes[0].content,/fiche de visite/);
const saved=(await store.getAllQuotes()).find(row=>row.id===lead.id);
assert.deepEqual(saved.technicalVisit,lead.technicalVisit);
await assert.rejects(async()=>store.updateQuoteLead(lead.id,{technicalVisit:visit,expectedUpdatedAt:'stale'}),{status:409});
lead=await store.updateQuoteLead(lead.id,{volume:3,unknownVolume:false});
assert.deepEqual(lead.technicalVisit,saved.technicalVisit);
const document=emptyQuoteDocument(lead);
assert.equal(document.fields.volume,'3');assert.equal(document.fields.departureElevator,'Non');assert.equal(document.fields.departureCarry,'25');assert.equal(document.fields.departureAccessNotes,access.notes);assert.equal(document.fields.arrivalElevator,'');
const existing={document:{...document,fields:{...document.fields,volume:'22',departureCarry:'10'}}};
assert.deepEqual(prefillQuoteDraft(existing,lead),existing,'Saved drafts remain unchanged');
console.log('Visite technique : validation, persistance, conflit, volume explicite, accès et devis existants vérifiés.');
