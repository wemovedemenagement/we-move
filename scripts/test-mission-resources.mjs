import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {missionResourceAvailability,missionCapacity} from '../shared/missionResources.mjs';
import {reviseRegistry,emptyRegistry} from '../server/crmPlanningModel.mjs';
const actor={role:'gerant',email:'test@example.invalid',name:'Contrôle isolé'};
const start='2026-11-17T08:00',end='2026-11-18T18:00';
const resources=[{id:'a',kind:'vehicle',name:'A',active:true,capacityM3:20},{id:'b',kind:'vehicle',name:'B',active:true,capacityM3:15.5},{id:'c',kind:'vehicle',name:'C',active:true,detail:'50 m³'},{id:'d',kind:'person',name:'D',active:true,unavailablePeriods:[{start,end,reason:'conges'}]}];
const bookings=[{leadId:'self',resourceIds:['a'],start,end},{leadId:'other',resourceIds:['b'],start:'2026-11-18T08:00',end:'2026-11-18T09:00'}];
const before=structuredClone({resources,bookings});
const result=missionResourceAvailability(resources,bookings,start,end,'self');
assert.equal(result.rows.find(r=>r.resource.id==='a').state,'available','Exclude only this mission');
assert.equal(result.rows.find(r=>r.resource.id==='b').reservations[0].leadId,'other');
assert.equal(result.rows.find(r=>r.resource.id==='d').absences[0].reason,'conges');
assert.equal(missionResourceAvailability(resources,bookings,'',end,'self').valid,false);
const lead={volume:35,unknownVolume:false};
assert.equal(missionCapacity(lead,resources,[]).state,'no_vehicle');
assert.equal(missionCapacity({...lead,unknownVolume:true},resources,['a']).state,'no_volume');
assert.equal(missionCapacity({...lead,volume:'invalid'},resources,['a']).state,'no_volume');
assert.equal(missionCapacity(lead,resources,['a']).state,'short');
assert.equal(missionCapacity(lead,resources,['a','b']).capacityM3,35.5);
assert.equal(missionCapacity(lead,resources,['a','b']).state,'covered');
assert.equal(missionCapacity(lead,resources,['a','a']).capacityM3,20,'Do not double count IDs');
assert.equal(missionCapacity(lead,resources,['a','c']).state,'unknown','Never infer capacity from detail');
assert.equal(missionCapacity(lead,resources,['a','c']).missing,1);
assert.deepEqual({resources,bookings},before);
const payload={revision:0,name:'Véhicule isolé',kind:'vehicle',active:true,detail:'Ancienne précision 30 m³'};
for(const capacityM3 of [0,-1,0.000000001,201,1.001,'20',Infinity,NaN,{},true])assert.throws(()=>reviseRegistry(emptyRegistry(),{...payload,capacityM3},actor),e=>e.status===400);
assert.throws(()=>reviseRegistry(emptyRegistry(),{...payload,kind:'person',capacityM3:20},actor),e=>e.status===400);
assert.throws(()=>reviseRegistry(emptyRegistry(),{...payload,capacityM3:20},{...actor,role:'secretaire'}),e=>e.status===403);
process.env.NODE_ENV='test';process.env.CRM_STORAGE='sqlite';process.env.CRM_LOCAL_ACCESS='true';process.env.CRM_DATA_DIR=mkdtempSync(path.join(tmpdir(),'wemove-mission-resources-'));process.env.CRM_LEAD_NOTIFICATIONS='false';process.env.CRM_CUSTOMER_RECEIPTS='false';process.env.CRM_BILLING_LIVE_ENABLED='false';
const store=await import('../server/crmStore.mjs');
let registry=await store.saveResource(payload,actor),vehicle=registry.resources[0];
assert.equal(vehicle.capacityM3,null);
registry=await store.saveResource({...payload,revision:registry.revision,id:vehicle.id,capacityM3:25.5},actor);
registry=await store.saveResource({...payload,revision:registry.revision,id:vehicle.id},actor);
assert.equal(registry.resources[0].capacityM3,25.5,'An older client must not erase capacity');
const attempts=await Promise.allSettled([store.saveResource({...payload,revision:registry.revision,id:vehicle.id,capacityM3:30},actor),store.saveResource({...payload,revision:registry.revision,id:vehicle.id,capacityM3:40},actor)]);
assert.equal(attempts.filter(r=>r.status==='fulfilled').length,1);assert.equal(attempts.find(r=>r.status==='rejected').reason.status,409);
registry=(await store.getPlanning()).registry;
registry=await store.saveResource({...payload,revision:registry.revision,id:vehicle.id,capacityM3:null},actor);
assert.equal((await store.getPlanning()).registry.resources[0].capacityM3,null,'Explicit clear is persisted');
console.log('Affectations : propre réservation exclue, conflits et absences conservés, capacités explicites, comparaison multi-véhicules, droits, validation, compatibilité et concurrence vérifiés.');
