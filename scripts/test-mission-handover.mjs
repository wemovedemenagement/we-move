import assert from 'node:assert/strict';
import {missionAgreementReview,missionAgreementChanges} from '../shared/missionHandover.mjs';
import {emptyQuoteDocument} from '../shared/quoteDocument.mjs';

const access={floor:'2',elevator:'Non',carry:'25',notes:'Passage étroit'};
const lead={id:'isolated',departureAddress:'Paris',arrivalAddress:'Versailles',volume:18,formula:'confort',technicalVisit:{items:[],departure:access,arrival:{floor:'0',elevator:'Oui',carry:'0',notes:''}},scheduledTime:'2026-11-01T08:00'};
const fields=emptyQuoteDocument(lead).fields;
Object.assign(fields,{departureStart:'2026-11-10',departureEnd:'2026-11-12'});
const acceptance={quoteRevision:2,quote:{id:lead.id,revision:2,document:{fields}}},quote={revision:2};
const review=(current=lead,booking=null)=>missionAgreementReview(current,quote,acceptance,booking);
const untouched=JSON.stringify({lead,quote,acceptance});
assert.deepEqual(review(),[],'Aucune ancienne date ne doit être prise pour une réservation actuelle');
assert.deepEqual(review({...lead,volume:'18.000',departureAddress:'  Paris \n '}),[]);
assert.deepEqual(review({...lead,departureFloor:'8',departureElevator:true}),[],'Le relevé de visite est prioritaire sur les anciens champs du site');
const changed={...lead,formula:'premium',technicalVisit:{...lead.technicalVisit,departure:{floor:'4',elevator:'Oui',carry:'0',notes:'Nouveau passage'},arrival:{floor:'0',elevator:'Non',carry:'00',notes:'Livrer par la cour'}}};
const rows=review(changed);
assert.deepEqual(rows.map(r=>r.key),['formula','departureFloor','departureElevator','departureCarry','departureAccessNotes','arrivalElevator','arrivalAccessNotes']);
assert.deepEqual(rows.find(r=>r.key==='departureCarry'),{key:'departureCarry',label:'Départ · portage',before:'25 m',current:'0 m',target:'visit',message:'Départ : portage à rapprocher du devis accepté.'});
assert.equal(rows.find(r=>r.key==='formula').target,'details');
assert.equal(rows.find(r=>r.key==='departureFloor').before,'2');
assert.equal(rows.find(r=>r.key==='departureFloor').current,'4');
assert.deepEqual(review({...lead,formula:'conseil',technicalVisit:{items:[],departure:{floor:'',elevator:'',carry:'',notes:''},arrival:{floor:'',elevator:'',carry:'',notes:''}}}),[],'Une absence de saisie ne signifie ni non ni zéro');
assert.deepEqual(review({...lead,technicalVisit:{...lead.technicalVisit,departure:{...access,carry:'025.00',notes:' Passage\n étroit '}}}),[]);
assert.equal(review({...lead,unknownVolume:true})[0].current,'À préciser');
assert.equal(review({...lead,departureAddress:'Lyon'})[0].target,'details');
assert.deepEqual(review(lead,{start:'2026-11-10T08:00'}),[]);
assert.deepEqual(review(lead,{start:'2026-11-12T23:00'}),[]);
assert.equal(review(lead,{start:'2026-11-13T08:00'})[0].target,'slot');
assert.equal(review(lead,{start:'2026-11-13T08:00'})[0].before,'10/11/2026 → 12/11/2026');
assert.deepEqual(review(lead,{start:'2026-11-13T08:00',cancelled:true}),[]);
assert.deepEqual(review(lead,{start:'2026-11-13T08:00',closure:{}}),[]);
assert.equal(missionAgreementReview(lead,{revision:3},acceptance,null)[0].target,'quote');
assert.equal(missionAgreementReview(lead,null,acceptance,null)[0].current,'Devis actuel indisponible');
assert.equal(missionAgreementReview(lead,quote,{quoteRevision:2},null)[0].key,'reference');
assert.deepEqual(missionAgreementReview(lead,quote,null,null),[]);
assert.match(missionAgreementChanges(lead,quote,acceptance)[0],/hors de la période/,'Compatibilité conservée pour les anciens appels sans réservation explicite');
assert.equal(JSON.stringify({lead,quote,acceptance}),untouched,'La comparaison ne modifie ni le dossier ni le devis accepté');
console.log('Avant départ : comparaison des accès, formules, volumes, valeurs zéro et inconnues, réservation réelle, corrections ciblées et conservation du devis accepté vérifiées.');
