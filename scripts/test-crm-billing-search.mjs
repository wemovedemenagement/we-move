assert.equal(new Set([1,2,3,4].flatMap(page=>run({page:String(page)}).documents.map(d=>d.id))).size,65);
assert.equal(run({search:'elodie rare'}).documents[0].id,'000');
assert.equal(run({search:'DEV-0'}).total,1);
assert.equal(run({status:'retard'}).total,1);
assert.equal(run({status:'refund'}).documents[0].id,'003');
assert.equal(run({status:'regle'}).total,1);
assert.equal(run({sort:'oldest'}).documents[0].id,'000');
assert.equal(run({sort:'due'}).documents[0].id,'001');
assert.equal(run({search:'Introuvable'}).total,0);
assert.ok(run({}).documents.every(d=>!d.payments&&!d.snapshot&&!d.pdfBase64));
