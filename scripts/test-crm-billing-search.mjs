import assert from 'node:assert/strict';
import { billingSearch } from '../server/crmBillingSearch.mjs';
const docs=Array.from({length:65},(_,i)=>({id:String(i).padStart(3,'0'),number:'F-'+i,mode:'live',kind:'facture',snapshot:{clientName:i===0?'Élodie Rare':'Client '+i},quoteReference:'DEV-'+i,createdAt:new Date(Date.UTC(2026,0,1+i)).toISOString(),issueDate:'2026-01-01',dueDate:'2026-12-01',amountTTC:10000,creditedTTC:0,payments:[]}));
docs[1].dueDate='2026-01-01';docs[2].payments=[{kind:'payment',amountCents:10000}];docs[3].creditedTTC=10000;docs[3].payments=[{kind:'payment',amountCents:1000}];
const records=[...docs,{...docs[0],mode:'test',id:'TEST'}];
const run=q=>billingSearch(records,q,'2026-10-01');
assert.equal(run({}).total,65);assert.equal(run({}).pages,4);assert.equal(run({}).documents.length,20);
assert.equal(run({page:'4'}).documents.length,5);
