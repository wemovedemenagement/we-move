import assert from 'node:assert/strict';
import {visitBucket,visitRows} from '../shared/crmVisits.mjs';
const today='2026-10-01',base={id:'1',status:'prise_contact'};
const bucket=p=>visitBucket({...base,...p},today);
assert.equal(bucket({}),null);
assert.equal(bucket({status:'visite_technique'}),'unplanned');
assert.equal(bucket({nextAction:{type:'visite',dueDate:today}}),'unplanned');
assert.equal(bucket({visitDate:today+'T09:00'}),'today');
assert.equal(bucket({visitDate:'2026-10-02T09:00'}),'upcoming');
assert.equal(bucket({visitDate:'2026-09-30T09:00'}),'review');
assert.equal(bucket({visitDate:'2026-02-30T09:00'}),'review');
assert.equal(bucket({visitDate:'Ancien créneau'}),'review');
assert.equal(bucket({visitDate:today}),'review');
assert.equal(bucket({visitDate:'2026-09-30T09:00',visitStatus:'effectuee'}),'done');
assert.equal(bucket({visitDate:today+'T09:00',status:'refuse'}),'closed');
assert.equal(bucket({status:'termine',nextAction:{type:'visite',dueDate:today}}),null);
const rows=visitRows([{...base,id:'future',visitDate:'2026-10-02T09:00'},{...base,id:'late',visitDate:'2026-09-29T09:00'},{...base,id:'today',visitDate:today+'T09:00'},{...base,id:'plan',status:'visite_technique'}],today);
assert.deepEqual(rows.map(r=>r.lead.id),['late','today','plan','future']);
console.log('Visites : dates Paris, visites passées, créneaux invalides, programmation, dossiers clos et tri validés.');
