import assert from 'node:assert/strict';
import {dossierAction} from '../shared/dossierWorkflow.mjs';
const data={lead:{status:'nouveau'},quote:null,mails:[],billing:[]};
assert.equal(dossierAction(data).target,'contact');
assert.equal(dossierAction({...data,lead:{status:'prise_contact',visitStatus:'effectuee'}}).target,'quote');
assert.equal(dossierAction({...data,quote:{revision:1,amountTTC:null}}).label,'Compléter le chiffrage');
const sent={...data,quote:{revision:1,amountTTC:100},mails:[{revision:1,state:'accepted',createdAt:'2026-10-02'}]};
assert.equal(dossierAction(sent).target,'followup');
assert.equal(dossierAction({...sent,quote:{revision:2,amountTTC:100}}).target,'quote');
assert.equal(dossierAction({...sent,mails:[{revision:1,state:'uncertain',createdAt:'2026-10-02'}]}).tone,'attention');
assert.equal(dossierAction({...data,lead:{status:'confirme'}}).target,'move');
const completed={...data,lead:{status:'termine'},billing:[{kind:'solde',dueCents:200,refundDueCents:0}]};
assert.equal(dossierAction(completed).label,'Suivre le règlement');
assert.equal(dossierAction(completed,false).target,'followup');
assert.equal(dossierAction({...completed,billing:[{kind:'solde',dueCents:0,refundDueCents:0}]}).label,'Consulter les règlements');
assert.equal(dossierAction({...completed,lead:{status:'refuse'}}).tone,'closed');
assert.equal(dossierAction({...data,lead:{status:'prise_contact',nextAction:{type:'facturer',dueDate:'2026-10-02'}}},false).target,'followup');
console.log('Dossier unique : progression, envois, révisions, règlements et restriction commerciale validés.');
const today='2026-10-02';
const visit={...data,lead:{status:'prise_contact',visitDate:'2026-09-30T10:00',visitStatus:'programmee',nextAction:{type:'visite',dueDate:'2026-09-30'}}};
assert.equal(dossierAction(visit,true,today).label,'Vérifier la visite passée');
assert.equal(dossierAction({...visit,lead:{...visit.lead,visitDate:'2026-10-02T14:00'}},true,today).badge,'Aujourd’hui');
assert.equal(dossierAction({...visit,lead:{...visit.lead,visitStatus:'effectuee'}},true,today).label,'Mettre à jour le suivi');
assert.equal(dossierAction({...visit,lead:{...visit.lead,status:'confirme'}},true,today).label,'Planifier le déménagement');
assert.equal(dossierAction({...visit,lead:{...visit.lead,status:'confirme',scheduledTime:'2026-10-01T08:00'}},true,today).label,'Vérifier le déménagement');
const late=dossierAction({...data,lead:{status:'devis_envoye',nextAction:{type:'relancer',dueDate:'2026-10-01',note:'Appeler le client'}}},true,today);
assert.equal(late.badge,'En retard');assert.match(late.reason,/Appeler le client.*2026-10-01/);
assert.equal(visit.lead.visitStatus,'programmee');assert.equal(visit.lead.nextAction.type,'visite');
console.log('Échéances : visites passées, visite du jour, action obsolète, mission passée et relance en retard validées.');
