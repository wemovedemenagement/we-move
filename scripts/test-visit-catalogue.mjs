import assert from 'node:assert/strict';
import {addVisitCatalogueItem,visitCatalogueResults} from '../shared/visitCatalogue.mjs';
import {normalizeTechnicalVisit,inventoryVolume} from '../shared/technicalVisit.mjs';

const armchair={name:'Fauteuil',subtitle:'Club ou relax',category:'Salon',m3:0.8};
const fridge={name:'Réfrigérateur',subtitle:'Grand modèle',category:'Cuisine',m3:1};
const access={floor:'0',elevator:'Non',carry:'0',notes:''};
const initial={items:[],departure:{...access},arrival:{...access}};
const before=structuredClone(initial);
let result=addVisitCatalogueItem(initial,armchair,'Séjour');
assert.equal(result.index,0);assert.equal(result.value.items[0].quantity,1);
assert.deepEqual(initial,before);
result=addVisitCatalogueItem(result.value,armchair,'Séjour');
assert.equal(result.value.items.length,1);assert.equal(result.value.items[0].quantity,2);assert.equal(inventoryVolume(result.value.items),1.6);
result=addVisitCatalogueItem(result.value,armchair,'Chambre');assert.equal(result.value.items.length,2);assert.equal(result.index,1);
const adjusted={...result.value,items:result.value.items.map((row,i)=>i===0?{...row,unitVolume:1.2}:row)};
result=addVisitCatalogueItem(adjusted,armchair,'Séjour');
assert.equal(result.value.items[0].unitVolume,1.2,'Une mesure déjà ajustée ne doit pas être écrasée par le catalogue');assert.equal(result.value.items.length,3);
assert.deepEqual(normalizeTechnicalVisit(result.value),result.value);
const full={...initial,items:Array.from({length:150},(_,i)=>({room:'Séjour',label:'Ligne '+i,quantity:1,unitVolume:1}))};
assert.throws(()=>addVisitCatalogueItem(full,armchair,'Séjour'),/150/);
const merged=addVisitCatalogueItem({...full,items:full.items.map((row,i)=>i===0?{...row,label:'Fauteuil',unitVolume:0.8}:row)},armchair,'Séjour');assert.equal(merged.value.items.length,150);assert.equal(merged.value.items[0].quantity,2);
assert.throws(()=>addVisitCatalogueItem({...initial,items:[{room:'Séjour',label:'Fauteuil',quantity:500,unitVolume:0.8}]},armchair,'Séjour'),/quantité maximale/);
for(const item of [{...armchair,m3:0},{...armchair,m3:Infinity},{...armchair,m3:101},{...armchair,name:''}])assert.throws(()=>addVisitCatalogueItem(initial,item,'Séjour'));
assert.throws(()=>addVisitCatalogueItem(initial,armchair,'Inconnue'));
assert.deepEqual(visitCatalogueResults([armchair,fridge],'','Séjour'),[armchair]);
assert.deepEqual(visitCatalogueResults([armchair,fridge],'REFRIGERATEUR grand','Séjour'),[fridge],'La recherche couvre le catalogue complet, sans distinction d’accent ou de casse');
assert.deepEqual(visitCatalogueResults([armchair,fridge],'','Autre'),[armchair,fridge]);
assert.deepEqual(visitCatalogueResults([armchair,fridge],'aucun resultat','Cuisine'),[]);
console.log('Catalogue de visite : recherche, pièce choisie, cumul explicite des quantités, conservation des mesures, limites et validation du relevé vérifiés sans mutation du dossier.');
