import assert from 'node:assert/strict';
import { billingExport, billingExportPeriod } from '../server/crmBillingExport.mjs';
const period={kind:'documents',from:'2026-01-01',to:'2026-01-31'};
const invoice={mode:'live',number:'F-001',kind:'facture',issueDate:'2026-01-01',dueDate:'2026-01-31',snapshot:{clientName:' =HYPERLINK("bad")'},amountHT:10000,taxAmount:2000,amountTTC:12000,creditedTTC:2400,payments:[{id:'p1',date:'2026-01-31',amountCents:5000,kind:'payment',method:'virement',reference:'Client; "référence"'},{id:'p2',date:'2026-01-02',amountCents:1000,kind:'refund'},{id:'p3',date:'2026-01-03',amountCents:2000,kind:'payment',reversedAt:'2026-02-01',reversalReason:'Erreur de saisie'}]};
const credit={...invoice,number:'A-002',kind:'avoir',amountHT:2000,taxAmount:400,amountTTC:2400,creditedTTC:0,creditNumber:'F-001',payments:[]};
const records=[invoice,credit,{...invoice,mode:'test',number:'TEST-1'},{...invoice,number:'F-OUT',issueDate:'2025-12-31',payments:[]}];
const result=billingExport(records,period);
assert.equal(result.count,2);
assert.ok(result.csv.startsWith('\uFEFF'));
assert.ok(result.csv.includes('"-20,00";"-4,00";"-24,00"'));
assert.ok(result.csv.includes('"\' =HYPERLINK(""bad"")"'));
assert.ok(!result.csv.includes('TEST-1'));
assert.ok(!result.csv.includes('F-OUT'));
const payments=billingExport(records,{...period,kind:'payments'});
assert.equal(payments.count,3);
assert.ok(payments.csv.includes('"-10,00"'));
assert.ok(payments.csv.includes('"Annulé";"0,00";"2026-02-01";"Erreur de saisie"'));
assert.ok(payments.csv.includes('"Client; ""référence"""'));
assert.equal(billingExport([{...invoice,issueDate:'2025-01-01'}],{...period,kind:'payments'}).count,3);
assert.equal(billingExport([],period).count,0);
for(const change of [{from:'2026-02-30'},{from:'2026-02-01'},{to:'2028-01-01'},{kind:'sql'},{from:['2026-01-01']},{from:'2026-01-01\r\nX:bad'}])assert.throws(()=>billingExportPeriod({...period,...change}),e=>e.status===400);
console.log('Exports : périodes, données réelles, avoirs, remboursements, annulations, montants et neutralisation des formules validés.');
