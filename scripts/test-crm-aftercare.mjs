import assert from 'node:assert/strict';
import {withMoveFollowUps} from '../shared/moveFollowUp.mjs';
import {workQueue,matchesWorkFilter} from '../shared/crmWorkflow.mjs';
import {crmNotifications} from '../shared/crmNotifications.mjs';
import {dossierAction} from '../shared/dossierWorkflow.mjs';
const today='2026-10-16';
const leads=['late','today','future','resolved','cancelled','refused','legacy'].map(id=>({id,status:id==='refused'?'refuse':'termine',moveFollowUp:{note:'Client forged value'}}));
const bookings=leads.filter(l=>l.id!=='legacy').map(l=>({leadId:l.id,cancelled:l.id==='cancelled',closure:{followUp:'Récupérer la lettre',owner:'Secrétariat',due:(l.id==='late'?'2026-10-15':l.id==='future'?'2026-10-17':today)+'T10:00',resolved:l.id==='resolved'}}));
const enriched=withMoveFollowUps(leads,bookings);
assert.equal(enriched.find(l=>l.id==='legacy').moveFollowUp,null);
assert.equal(enriched.find(l=>l.id==='resolved').moveFollowUp,null);
assert.equal(enriched.find(l=>l.id==='cancelled').moveFollowUp,null);
assert.equal(leads[0].moveFollowUp.note,'Client forged value','Projection must not mutate input');
assert.equal(withMoveFollowUps([{id:'blank'}],[{leadId:'blank',closure:{followUp:' \n '}}])[0].moveFollowUp,null);
const queue=workQueue(enriched,today);
assert.deepEqual(queue.filter(r=>matchesWorkFilter(r,'aftercare',today)).map(r=>r.lead.id),['late','today','future']);
assert.deepEqual(queue.filter(r=>matchesWorkFilter(r,'urgent',today)).map(r=>r.lead.id),['late','today']);
assert.deepEqual(crmNotifications(enriched,today).map(r=>r.lead.id),['late','today']);
for(const canInvoice of [true,false])assert.equal(dossierAction({lead:enriched[0]},canInvoice,today).target,'move');
assert.equal(dossierAction({lead:enriched.find(l=>l.id==='resolved')},true,today).target,'invoice');
console.log('Après-mission : projection réelle, dossiers anciens, annulations, résolution, priorités, échéances, notifications et action dossier vérifiés.');
