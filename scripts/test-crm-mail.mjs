import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {PDFDocument} from 'pdf-lib';
process.env.CRM_STORAGE='sqlite';
process.env.CRM_MAIL_PROVIDER='smtp';
process.env.CRM_SMTP_PASSWORD='';
process.env.CRM_DATA_DIR=mkdtempSync(join(tmpdir(),'wemove-mail-'));
const store=await import('../server/crmStore.mjs');
const {sendQuoteMail,prepareQuoteMail}=await import('../server/crmMail.mjs');
const lead=await store.createQuoteLead({fullName:'Contrôle local',email:'test@example.invalid',phone:'0612345678',source:'telephone'});
let d=await store.createQuoteDraft(lead.id);
Object.assign(d.document.fields,{clientAddress:'Adresse de test',departureAddress:'Départ test',arrivalAddress:'Arrivée test',formula:'MOVE Confort',issueDate:'2026-01-01',departureStart:'2099-01-01',arrivalStart:'2099-01-01',guarantee:'Responsabilité contractuelle',coveredValue:'5000',itemLimit:'1500',paymentKind:'Arrhes',balanceWhen:'À la livraison'});
const payload=()=>({revision:d.revision,items:[{description:'Test isolé',quantity:1,unitPriceHT:100}],taxRate:20,depositRate:30,validUntil:'2099-01-01',notes:'',document:d.document});
d=await store.saveQuoteDraft(d.id,payload());
const actor={role:'gerant',email:'local@example.invalid'},configuration=()=>({ready:true,from:'sender@example.invalid'});
const body=()=>({confirm:true,revision:d.revision,subject:'Votre devis',message:'Message de contrôle local'});
let count=0;
const transport=async message=>{count++;assert.equal(message.to.address,'test@example.invalid');assert.equal(message.attachments.length,1);assert.equal((await PDFDocument.load(message.attachments[0].content)).getPageCount(),5);return {accepted:['test@example.invalid'],messageId:'local-test'};};
assert.deepEqual((await prepareQuoteMail(d.id)).issues,[]);
await assert.rejects(sendQuoteMail(d.id,body(),{role:'inconnu'},{transport,configuration}),e=>e.status===403);
await assert.rejects(sendQuoteMail(d.id,{...body(),confirm:false},actor,{transport,configuration}),e=>e.status===400);
await assert.rejects(sendQuoteMail(d.id,{...body(),subject:'Injection\r\nBcc: other@example.invalid'},actor,{transport,configuration}),e=>e.status===400);
await assert.rejects(sendQuoteMail(d.id,{...body(),revision:0},actor,{transport,configuration}),e=>e.status===409);
await assert.rejects(sendQuoteMail(d.id,body(),actor,{transport,configuration:()=>({ready:false,message:'Non configuré'})}),e=>e.status===409);
const sent=await sendQuoteMail(d.id,body(),actor,{transport,configuration});assert.equal(sent.state,'accepted');
await sendQuoteMail(d.id,body(),actor,{transport,configuration});assert.equal(count,1);
const archive=(await store.getQuoteMails(d.id))[0];assert.ok(archive.pdfBase64);assert.ok(archive.sha256);assert.equal(archive.snapshot.reference,sent.reference);assert.ok(archive.snapshot.issuedAt);
assert.equal((await store.getQuoteDrafts())[0].emailDelivery.state,'accepted');
assert.equal('pdfBase64' in (await prepareQuoteMail(d.id)).history[0],false);
d=await store.saveQuoteDraft(d.id,payload());
const uncertain=await sendQuoteMail(d.id,body(),actor,{configuration,transport:async()=>{throw new Error('timeout');}});assert.equal(uncertain.state,'uncertain');
await assert.rejects(sendQuoteMail(d.id,body(),actor,{configuration,transport}),e=>e.status===409);assert.equal(count,1);
d=await store.saveQuoteDraft(d.id,payload());
const results=await Promise.allSettled([sendQuoteMail(d.id,body(),actor,{configuration,transport}),sendQuoteMail(d.id,body(),actor,{configuration,transport})]);
assert.ok(results.some(r=>r.status==='fulfilled'));assert.equal(count,2);
console.log('E-mails : validation, autorisation, version figée, archivage privé, double clic et résultat incertain vérifiés sans aucun e-mail réel.');
