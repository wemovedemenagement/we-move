import assert from 'node:assert/strict';
import {departureReadiness} from '../shared/departureReadiness.mjs';
const registry={resources:[{id:'v',kind:'vehicle',active:true},{id:'p',kind:'person',active:true}]};
const lead={id:'a',status:'confirme',departureAddress:'Paris',arrivalAddress:'Lyon',volume:20,phone:'0100000000'};
const base={leadId:'a',start:'2026-10-15T08:00',end:'2026-10-15T18:00',resourceIds:['v','p']};
const row=(b=base,l=lead,r=registry,days=7)=>departureReadiness([l],[b],r,'2026-10-15',days);
assert.equal(row()[0].issues.length,6,'Old missions require preparation checks');
assert.equal(row({...base,start:'2026-10-14T08:00',end:'2026-10-15T09:00'}).length,1,'Include ongoing multiday missions');
assert.equal(row({...base,end:'2026-10-15T00:00'}).length,0);
assert.equal(row({...base,start:'2026-10-22T00:00',end:'2026-10-22T18:00'}).length,0);
assert.equal(row({...base,start:'2026-10-21T08:00',end:'2026-10-21T18:00'}).length,1);
for(const b of [{...base,cancelled:true},{...base,closure:{}}])assert.equal(row(b).length,0);
for(const status of ['termine','refuse'])assert.equal(row(base,{...lead,status}).length,0);
assert.ok(row(base,{...lead,unknownVolume:true})[0].issues.some(i=>i.label==='Volume à préciser'&&i.target==='details'));
assert.ok(row(base,{...lead,status:'devis_envoye'})[0].issues.some(i=>i.target==='summary'));
assert.ok(row(base,lead,{resources:[{...registry.resources[0],unavailablePeriods:[{start:base.start,end:base.end}]},registry.resources[1]]})[0].issues.some(i=>i.label.startsWith('Indisponibilité')));
assert.equal(departureReadiness([], [base],registry,'2026-10-15')[0].issues[0].target,'summary');
assert.equal(row({...base,start:'2026-10-16T00:00',end:'2026-10-16T18:00'},lead,registry,1).length,0);
assert.equal(row(base,lead,registry,2).length,0);
console.log('Avant départ : préparation ancienne, destinations des corrections, volume inconnu, absences, périodes, multijour et exclusions vérifiés.');
