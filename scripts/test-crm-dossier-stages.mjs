import assert from 'node:assert/strict';
import {dossierStages} from '../shared/dossierStages.mjs';
const today='2026-10-03';
const base={lead:{status:'nouveau'},quote:null,mails:[],billing:[]};
const stage=(data,id,finance=true)=>dossierStages(data,finance,today).find(s=>s.id===id);
assert.equal(stage(base,'visit').state,'optional');
assert.equal(stage(base,'invoice',false),undefined);
const scheduled={...base,lead:{status:'confirme',visitDate:'2026-10-02T10:00',scheduledTime:'2026-10-02T08:00'}};
assert.equal(stage(scheduled,'visit').state,'attention');
assert.equal(stage(scheduled,'move').state,'attention');
assert.equal(stage({...scheduled,lead:{...scheduled.lead,status:'termine',visitStatus:'effectuee'}},'move').state,'done');
const mailed={...base,quote:{revision:2},mails:[{createdAt:'2026-10-02',revision:1,state:'accepted'}]};
assert.equal(stage(mailed,'quote').detail,'Version enregistrée');
mailed.mails.push({createdAt:'2026-10-03',revision:2,state:'accepted'});
assert.equal(stage(mailed,'quote').detail,'Transmis par e-mail');
assert.equal(stage(mailed,'acceptance').state,'pending');
mailed.mails.push({createdAt:'2026-10-04',revision:2,state:'uncertain'});
assert.equal(stage(mailed,'quote').state,'attention');
const paid={...base,billing:[{kind:'acompte',dueCents:0,refundDueCents:0}]};
assert.equal(stage(paid,'invoice').detail,'Factures enregistrées réglées');
assert.equal(stage(paid,'move').state,'pending');
const refund={...scheduled,lead:{...scheduled.lead,status:'refuse'},billing:[{kind:'avoir',refundDueCents:100}]};
assert.equal(stage(refund,'visit').state,'closed');
assert.equal(stage(refund,'invoice').state,'attention');
assert.equal(stage({...base,billing:[{kind:'avoir',refundDueCents:0}]},'invoice').state,'pending');
console.log('Parcours dossier : étapes facultatives, révisions, acceptation explicite, échéances, rôles et règlements validés.');
