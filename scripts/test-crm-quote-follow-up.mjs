import assert from 'node:assert/strict';
import { quoteFollowUp } from '../shared/quoteFollowUp.mjs';
import {quoteListPriority,compareQuotePriority} from '../shared/quoteListPriority.mjs';
import {quotePrimaryAction} from '../shared/quotePrimaryAction.mjs';
const draft={revision:3,emailDelivery:{revision:3,state:'accepted'}};
const lead={status:'devis_envoye',nextAction:null};
const read=(d=draft,l=lead)=>quoteFollowUp(d,l,'2026-10-01');
assert.equal(read().waiting,true);assert.equal(read().unscheduled,true);
assert.equal(read().nextAction.timing,'missing');assert.equal(read().nextAction.label,'À définir');assert.equal(read().nextAction.owner,'Non attribué');
assert.equal(read(draft,null).nextAction,null);
for(const status of ['confirme','refuse','termine'])assert.equal(read(draft,{status,nextAction:{type:'relancer',dueDate:'2026-09-30'}}).nextAction,null);
for(const [dueDate,timing,label] of [['2026-09-30','overdue','En retard'],['2026-10-01','today','Aujourd’hui'],['2026-10-02','future','À venir']]){
 const action=read(draft,{...lead,assigneeId:'member-real',assigneeName:'Camille',nextAction:{type:'rappeler',dueDate}}).nextAction;
 assert.equal(action.timing,timing);assert.equal(action.label,label);assert.equal(action.date,dueDate);assert.equal(action.title,'Rappeler');assert.equal(action.owner,'Camille');
}
assert.equal(read(draft,{...lead,assigneeId:'member-real',nextAction:{type:'relancer',dueDate:'2026-10-02'}}).nextAction.owner,'Responsable à vérifier');
assert.equal(read(draft,{...lead,assigneeName:'Ancien nom sans affectation',nextAction:{type:'relancer',dueDate:'2026-10-02'}}).nextAction.owner,'Non attribué');
assert.equal(read({...draft,emailDelivery:undefined},lead).nextAction,null,'A draft without follow-up does not acquire an invented task');
assert.equal(read({...draft,revision:4}).deliveryLabel,'Modifié depuis l’envoi');
assert.equal(read({...draft,revision:4}).waiting,false);
assert.equal(read({...draft,emailDelivery:{revision:3,state:'uncertain'}}).mailIssue,true);
assert.equal(read({...draft,emailDelivery:{revision:3,state:'sending'}}).deliveryLabel,'Envoi en cours');
assert.equal(read({...draft,emailDelivery:{revision:3,state:'failed'}}).deliveryLabel,'Envoi refusé');
for(const status of ['confirme','refuse','termine']) {const f=read(draft,{status,nextAction:{type:'relancer',dueDate:'2026-09-30'}});assert.equal(f.waiting,false);assert.equal(f.followDue,false);}
assert.equal(read(draft,null).waiting,false);
assert.equal(read(draft,{...lead,nextAction:{type:'relancer',dueDate:'2026-10-01'}}).followDue,true);
assert.equal(read(draft,{...lead,nextAction:{type:'rappeler',dueDate:'2026-09-30'}}).overdue,true);
assert.equal(read(draft,{...lead,nextAction:{type:'relancer',dueDate:'2026-10-02'}}).followDue,false);
assert.equal(read(draft,{...lead,nextAction:{type:'facturer',dueDate:'2026-09-30'}}).followDue,false);
for(const dueDate of ['',undefined,null,'2026-02-30','2026-9-30',{},'2026-09-30T10:00:00Z']){
 const follow=read(draft,{...lead,nextAction:{type:'relancer',dueDate}});
 assert.equal(follow.followDue,false);assert.equal(follow.overdue,false);assert.ok(follow.actionLabel.includes('Échéance à préciser'));
 assert.equal(follow.nextAction.timing,'undated');assert.equal(follow.nextAction.label,'Date à préciser');assert.equal(follow.nextAction.date,'');
}
const today='2026-10-01',rows=[],leads=new Map();
const add=(id,change={},leadChange={})=>{
 const row={id,leadId:id,updatedAt:'2026-10-01T10:00:00Z',amountTTC:1200,validUntil:'2026-10-15',...draft,...change};
 rows.push(row);leads.set(id,{...lead,...leadChange});return row;
};
add('closed-accepted',{emailDelivery:{state:'uncertain',revision:3}},{status:'confirme',nextAction:{type:'relancer',dueDate:'2026-09-01'}});
add('future-later',{}, {nextAction:{type:'rappeler',dueDate:'2026-10-10'}});
add('unpriced',{amountTTC:null,emailDelivery:undefined});
add('overdue-newer',{}, {nextAction:{type:'relancer',dueDate:'2026-09-30'}});
add('expired',{validUntil:'2026-09-20'});
add('mail-issue',{emailDelivery:{state:'uncertain',revision:3}});
add('no-next-action');
add('future-sooner',{}, {nextAction:{type:'relancer',dueDate:'2026-10-02'}});
add('today',{}, {nextAction:{type:'relancer',dueDate:today}});
add('overdue-older',{}, {nextAction:{type:'rappeler',dueDate:'2026-09-15'}});
